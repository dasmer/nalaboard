import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createContext,runInContext} from 'node:vm';
const source=readFileSync(new URL('../client.js',import.meta.url),'utf8').replace(/^import .*\n/,'');
const handlers={}, navigations=[];
const nodes=Object.fromEntries(['#app','#modal-root','#toast'].map(id=>[id,{innerHTML:'',style:{},classList:{add(){},remove(){}}}]));
const context=createContext({console,Intl,URL,Set,Map,crypto,location:{pathname:'/',hash:'#players',origin:'https://nalaboard.com',assign:url=>navigations.push(url)},history:{replaceState(){}},document:{querySelector:s=>nodes[s]||null,body:{style:{}},addEventListener:(name,handler)=>{handlers[name]=handler;}},window:{addEventListener(){},scrollTo(){}},requestAnimationFrame:fn=>fn(),setTimeout:()=>0,clearTimeout(){},FormData:class{constructor(form){return Object.entries(form.values);}}});
runInContext(source.slice(0,source.lastIndexOf('\n$("#app").innerHTML =')),context);
const run=code=>runInContext(code,context);
context.fixture={players:[{id:'a',name:'Alice',username:'alice',active:true},{id:'b',name:'David',username:'david',active:false}],matches:[],activity:[],keys:[],user:{id:'a',name:'Alice',username:'alice',active:true},standings:{all:[{id:'b',played:1,wins:1,losses:0,rate:100}],week:[{id:'b',played:1,wins:1,losses:0,rate:100}],month:[]},rivalries:[],pagination:{}};
run('data=fixture;modal=html=>{globalThis.dialog=html;};toast=()=>{};');
assert.ok(!run('players()').includes('David'),'Inactive player excluded from normal roster');
assert.ok(!run('players()').includes('player-status-filter'),'Non-admin has no management filters');
assert.ok(run("profile('b')").includes('David'));
assert.ok(run("profile('b')").includes('Inactive'));
assert.ok(!run("profile('b')").includes('data-action="record"'),'Inactive profile has no invitation to record');
assert.ok(!run("profile('b')").includes('data-action="player-status"'),'Non-admin has no status controls');
run('chooseOpponent()');assert.ok(!context.dialog.includes('David'),'Inactive opponent excluded from picker');
assert.equal(run("board(null,'week').length"),0,'Current standings exclude inactive players even with stale totals');
assert.equal(run("board(null,'all')[0].name"),'David','Historical standings preserved');
const regularRoster=run('players()'), regularProfile=run("profile('b')");
run('data.playerAdmin=true;playerStatusFilter="inactive";');
assert.equal(run('players()'),regularRoster,'Admins see the same roster');
assert.equal(run("profile('b')"),regularProfile,'Admins see the same player card');
assert.ok(run('adminPlayers()').includes('David'));assert.ok(!run('adminPlayers()').includes('href="/#profile/a"'));
assert.ok(run('adminPlayers()').includes('Reactivate'));
run('playerStatusFilter="active";');
assert.ok(!run('adminPlayers()').includes('data-player-id="a"'),'Self-deactivation hidden');
run("location.pathname='/admin';location.hash='#players';renderAdmin();");
assert.ok(nodes['#app'].innerHTML.includes('Search players'));
run('data.playerAdmin=false;renderAdmin();');
assert.ok(nodes['#app'].innerHTML.includes('Admin access required.'));
assert.ok(!nodes['#app'].innerHTML.includes('data-action="player-status"'));
run('data.user=null;renderAdmin();');
assert.ok(nodes['#app'].innerHTML.includes('Sign in to manage Nalaboard.'));
run('data.user=fixture.players[0];data.displayAdmin=true;data.displays=[{id:"33333333-3333-4333-8333-333333333333",last_seen_at:"2026-11-08T10:00:00Z"}];renderAdmin();');
assert.ok(nodes['#app'].innerHTML.includes('Connected big screens'));
assert.ok(!nodes['#app'].innerHTML.includes('data-action="player-status-filter"'),'Display-only role gets no player controls');
run('data.playerAdmin=true;account();');
assert.ok(context.dialog.includes('href="/admin"'));
assert.ok(!context.dialog.includes('/activate#displays'));
assert.ok(context.dialog.includes('href="/#profile/a"'),'Account links leave the admin path');
await handlers.submit({preventDefault(){},target:{dataset:{form:'admin-activate'},values:{code:' 7a51f-f4b48 '},querySelector:()=>null}});
assert.equal(navigations.at(-1),'/activate?code=7A51F-F4B48','Code entry reuses the existing approval route');
await run("action({dataset:{action:'player-status',playerId:'b'}})");
assert.ok(context.dialog.includes('Reactivate David?'));assert.ok(context.dialog.includes('data-active="true"'));
run("data.players[1].active=true");
await run("action({dataset:{action:'player-status',playerId:'b'}})");
assert.ok(context.dialog.includes('Deactivate David?'));assert.ok(context.dialog.includes('data-active="false"'));
console.log('Admin UI passed: identical public roster/cards, dedicated role-gated player and big-screen controls, direct activation handoff and confirmation direction.');

// A failed refresh after a successful status write must not throw against a closed dialog.
run("api=async()=>({ok:true});closeModal=()=>{};refresh=async()=>{throw Error('Offline');};toast=message=>{globalThis.notice=message;};");
await run("action({dataset:{action:'confirm-player-status',playerId:'b',active:'false'}})");
assert.equal(context.notice,'Offline');
